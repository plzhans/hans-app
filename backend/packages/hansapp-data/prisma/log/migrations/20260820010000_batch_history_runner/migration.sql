-- 회차를 누가 돌렸는지 남긴다.
--
-- **어디서 도는지 모르는 상태가 실제로 벌어져서 넣는다.** 옛 빌드가 어딘가에 떠서 5분마다
-- 회차를 만드는데, 이력에 실행 주체가 없어 어느 호스트인지 특정하지 못했다. 잡 이름이
-- 예전 것(daily-sync)이라는 정황으로 "옛 빌드다" 까지만 좁혔을 뿐이다.
--
-- 설계 때는 "인스턴스가 하나뿐이라 전부 같은 값이 들어간다" 며 뺐다. 그 판단이 틀렸다 —
-- 값이 같은 것과 값이 없는 것은 다르고, 하나뿐이라는 전제가 깨지는 순간 추적할 근거가
-- 통째로 사라진다.
--
-- version 이 특히 값을 한다. 0.0.1+a1b2c3d 형태라 **어느 빌드인지가 바로 드러난다.**
-- 기존 행은 전부 NULL 로 남는다(그때는 안 적었다는 뜻이라 그대로가 맞다).

ALTER TABLE `batch_job_history`
    ADD COLUMN `hostname` VARCHAR(64) NULL,
    ADD COLUMN `pid` INTEGER NULL,
    ADD COLUMN `version` VARCHAR(50) NULL;
