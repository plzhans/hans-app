-- 배치 잡 스케줄 on/off.
--
-- 관리자가 콘솔에서 잡의 스케줄을 끌 수 있게 한다. 문제가 생긴 잡을 배포 없이 멈추는
-- 수단이 지금까지 없었다 — 설정을 고쳐 재배포하거나 배치를 통째로 내리는 수밖에 없었다.
--
-- **이 표에서 유일하게 DB 가 정본인 열이다.** 설명·분류·크론식은 부팅 때 코드가 덮어쓰는
-- 거울이지만, 이 값은 사람이 끈 것이라 재부팅으로 되살아나면 안 된다. 등록 시 upsert 가
-- status 와 함께 이 열을 건드리지 않는다.
--
-- **스케줄만 끈다.** hanscli 나 --job 으로 직접 돌리는 길은 열어 둔다 — 껐다는 것은
-- "정해진 시각에 저절로 돌지 마라" 이지 "이 작업을 봉인하라" 가 아니다.
-- 기존 잡은 전부 켜진 상태로 남는다(DEFAULT true).

ALTER TABLE `batch_job`
    ADD COLUMN `enabled` BOOLEAN NOT NULL DEFAULT true;
