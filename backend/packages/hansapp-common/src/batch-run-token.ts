/**
 * 관리자 콘솔이 배치에 "지금 실행" 을 요청할 때 쓰는 토큰의 약속.
 *
 * **서명하는 쪽(admin-api)과 검증하는 쪽(batch)이 같은 값을 봐야 해서 여기 모은다.**
 * 양쪽에 문자열을 따로 적으면 어긋났을 때 조용히 401 이 되고, 그 실패는 "키가 틀렸나"
 * "주소가 틀렸나" 와 구별이 안 된다.
 */

/**
 * 이 토큰을 받을 쪽(aud).
 *
 * **같은 키로 서명된 다른 토큰을 거르는 장치다.** 관리자 access token 도 같은 키로 서명되므로
 * (발급자 키 하나가 여러 대상에게 서명하는 것은 정상이다), 배치가 aud 를 확인하지 않으면
 * 관리자가 로그인할 때 받은 토큰을 그대로 배치에 들이밀 수 있다.
 */
export const BATCH_RUN_AUDIENCE = 'hansapp-batch';

/**
 * 토큰 수명(초). 한 번의 호출이 오가는 시간이면 충분하다.
 *
 * 짧게 잡는 것이 이 설계에서 로그 유출에 대한 답이다 — 어딘가에 찍혀도 그때는 이미 죽어 있다.
 * 두 프로세스의 시계가 조금 어긋나도 견디도록 한 자릿수 초는 피한다.
 */
export const BATCH_RUN_TOKEN_TTL_SEC = 30;

/**
 * 무엇을 돌리는가.
 *
 * **두 층위가 있다.** 잡(`hira`)은 그 기관의 단계를 순서대로 다 돌리고, 단계(`hira.7`)는
 * 그 하나만 돌린다. 이름 공간이 겹치지 않지만(잡에는 점이 없다) 종류를 토큰에 박아 둔다 —
 * 한쪽으로 발급한 토큰이 다른 쪽 경로에서 쓰이는 일을 이름 규칙에 기대지 않으려는 것이다.
 */
export type BatchRunTarget = 'job' | 'stage';

/** 토큰에 담기는 것. 클레임 이름이 양쪽에서 같아야 한다. */
export interface BatchRunTokenClaims {
  /** 누가 눌렀나(관리자 계정 id). 배치 로그에도 남는다. */
  readonly sub: string;
  /** 잡 전체인가 단계 하나인가. 배치가 경로와 대조한다. */
  readonly kind: BatchRunTarget;
  /**
   * 무엇을 돌릴지. 잡 이름(`hira`) 또는 단계 키(`hira.7`).
   *
   * **배치가 URL 경로와 대조한다** — 토큰을 가로채도 그 하나로 묶인다.
   */
  readonly job: string;
  /**
   * 이미 받은 것도 다시 받을지. 최근에 성공한 단계도 돌고 받아 둔 병원도 다시 조회한다.
   *
   * **원본 호출을 크게 쓰는 선택이라 토큰에 박아 둔다** — 본문으로 받으면 서명된 값과
   * 그냥 실린 값이 공존하게 된다.
   *
   * **꺼진 단계를 뚫는 것과는 다른 얘기다.** 관리자 화면에서 부른 실행은 이 값과 무관하게
   * 꺼진 단계도 돈다 — 사람이 그것을 콕 집어 눌렀기 때문이다.
   */
  readonly force: boolean;
}
